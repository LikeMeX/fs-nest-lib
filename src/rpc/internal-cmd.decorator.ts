import 'reflect-metadata';

/**
 * Metadata key used by @InternalCmd to tag methods in the dispatch registry.
 * @internal
 */
export const INTERNAL_CMD_METADATA = 'internal:cmd';

/**
 * Registry of all cmd → method mappings collected via @InternalCmd.
 * Populated at class decoration time; consumed by InternalRpcDispatcher.
 * @internal
 */
export interface CmdHandlerEntry {
  cmd: string;
  methodName: string;
  /** The class prototype that owns the method (set by collectCmds). */
  target?: object;
}

/**
 * @InternalCmd('CMD_NAME') method decorator.
 *
 * Marks a service method as the handler for a specific cmd string.
 * The same method is invoked both by:
 * - `POST /internal/rpc {cmd, payload}` tunnel (via InternalRpcController)
 * - The deterministic REST route generated by cmdToRoute (Phase 2)
 *
 * Usage:
 * ```ts
 * class CourseService {
 *   @InternalCmd('GET_COURSE')
 *   getCourse(payload: { id: string }): Promise<Course> { ... }
 * }
 * ```
 *
 * Then register with InternalRpcDispatcher.register(new CourseService(), collectCmds(CourseService)).
 */
export function InternalCmd(cmd: string): MethodDecorator {
  return (target: object, propertyKey: string | symbol): void => {
    const existing: CmdHandlerEntry[] =
      Reflect.getMetadata(INTERNAL_CMD_METADATA, target.constructor) ?? [];
    existing.push({ cmd, methodName: String(propertyKey) });
    Reflect.defineMetadata(INTERNAL_CMD_METADATA, existing, target.constructor);
  };
}

/**
 * Collect all @InternalCmd entries from a class constructor.
 *
 * @param target - The class constructor (e.g. `CourseService`).
 * @returns Array of { cmd, methodName } entries.
 *
 * @example
 * const entries = collectCmds(CourseService);
 * // [{ cmd: 'GET_COURSE', methodName: 'getCourse' }]
 */
export function collectCmds(target: new (...args: unknown[]) => unknown): CmdHandlerEntry[] {
  return Reflect.getMetadata(INTERNAL_CMD_METADATA, target) ?? [];
}
